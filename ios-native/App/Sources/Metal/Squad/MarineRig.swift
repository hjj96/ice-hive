    /// Add clip `c` at time t (s; loops wrap, one-shots clamp) with weight w; `shift` (model xz) is taken off its pelvis
    /// (a clip's travel already moved into the visual offset).
    private func acc(_ c: Int, time t: Float, _ w: Float, shift: SIMD2<Float> = .zero, rot: Float = 0) {
        let rq = rot != 0 ? Quat.axis(F3(0, 1, 0), -rot) : Quat.identity
        if w <= 1e-4 { return }
        let C = asset.clips[c]
        let fr = Float(C.frames)
        var p = t * asset.fps
        if C.loop { p = p - floorf(p / fr) * fr } else { p = min(max(0, p), fr - 1) }
        let f0 = Int(p), fa = p - Float(f0)
        let f1 = C.loop ? (f0 + 1) % C.frames : min(f0 + 1, C.frames - 1)
        let r0 = (C.first + min(f0, C.frames - 1)) * n, r1 = (C.first + f1) * n
        for b in 0..<n {
            if b == asset.iCtrl {
                let a = asset.pos[r0 + b], bb = asset.pos[r1 + b]
                ctrlAcc += (a + (bb - a) * fa) * w
                ctrlVisor += (asset.rot[r0 + b].x + (asset.rot[r1 + b].x - asset.rot[r0 + b].x) * fa) * w
                continue
            }
            var q = Quat.nlerp(asset.rot[r0 + b], asset.rot[r1 + b], fa)
            if rot != 0 && b == asset.iPelvis { q = Quat.norm(Quat.mul(rq, q)) }
            if (q * accQ[b]).sum() < 0 { q = -q }
            accQ[b] += q * w
            let a = asset.pos[r0 + b], bb = asset.pos[r1 + b]
            var tr = F3(a.x + (bb.x - a.x) * fa, a.y + (bb.y - a.y) * fa, a.z + (bb.z - a.z) * fa)
            if b == asset.iPelvis {
                tr.x -= shift.x; tr.z -= shift.y
                if rot != 0 { tr = Quat.rotate(rq, tr) }
            }
            accT[b] += tr * w
        }
        accW += w
    }

    /// Locomotion clips are sampled by phase (0…1).
    private func accPhase(_ c: Int, _ ph: Float, _ w: Float) {
        acc(c, time: ph * asset.clips[c].duration, w)
    }

    private func endAcc(into q: inout [Q], _ t: inout [F3]) {
        let inv = accW > 1e-6 ? 1 / accW : 1
        for b in 0..<n where b != asset.iCtrl {
            q[b] = Quat.norm(accQ[b])
            t[b] = accT[b] * inv
        }
        q[asset.iCtrl] = Quat.identity
        t[asset.iCtrl] = .zero
    }

    /// Delta of an additive clip at t against its frame 0, applied on top of the pose (pre-multiplied, local).
    private func additive(_ c: Int, time t: Float, _ w: Float) {
        if w <= 1e-3 { return }
        let C = asset.clips[c]
        let fr = Float(C.frames)
        var p = t * asset.fps
        if C.loop { p = p - floorf(p / fr) * fr } else { p = min(max(0, p), fr - 1) }
        let f0 = Int(p), fa = p - Float(f0)
        let f1 = C.loop ? (f0 + 1) % C.frames : min(f0 + 1, C.frames - 1)
        let r0 = (C.first + f0) * n, r1 = (C.first + f1) * n, rr = C.first * n
        for b in 0..<n where b != asset.iCtrl {
            let q = Quat.nlerp(asset.rot[r0 + b], asset.rot[r1 + b], fa)
            var d = Quat.mul(q, Quat.conj(asset.rot[rr + b]))
            d = Quat.nlerp(Quat.identity, d, w)
            lq[b] = Quat.norm(Quat.mul(d, lq[b]))
            let a = asset.pos[r0 + b], bb = asset.pos[r1 + b], ref = asset.pos[rr + b]
            let dt = F3(a.x + (bb.x - a.x) * fa - ref.x, a.y + (bb.y - a.y) * fa - ref.y, a.z + (bb.z - a.z) * fa - ref.z)
            lt[b] += dt * w
        }
    }

    // ---------------------------------------------------------------- FK / IK
    private func fk() {
        for b in 0..<n {
            let p = asset.parent[b]
            if p < 0 { wq[b] = lq[b]; wt[b] = lt[b] } else {
                wq[b] = Quat.norm(Quat.mul(wq[p], lq[b]))
                wt[b] = wt[p] + Quat.rotate(wq[p], lt[b])
            }
        }
    }

    /// FK of one bone's subtree after a local change (bones are ordered parents first: the mask's bits ascend).
    private func fkFrom(_ root: Int) {
        var m = subtree[root]
        while m != 0 {
            let b = m.trailingZeroBitCount
            m &= m - 1
            let p = asset.parent[b]
            if p < 0 { wq[b] = lq[b]; wt[b] = lt[b] } else {
                wq[b] = Quat.norm(Quat.mul(wq[p], lq[b]))
                wt[b] = wt[p] + Quat.rotate(wq[p], lt[b])
            }
        }
    }

    /// Give bone b the model-space rotation q (its parent's from the current FK).
    private func setWorld(_ b: Int, _ q: Q) {
        let p = asset.parent[b]
        lq[b] = p >= 0 ? Quat.norm(Quat.mul(Quat.conj(wq[p]), q)) : q
    }

    /// FK of one bone whose parent is already posed (no subtree).
    @inline(__always) private func fkOne(_ b: Int) {
        let p = asset.parent[b]
        if p < 0 { wq[b] = lq[b]; wt[b] = lt[b] } else {
            wq[b] = Quat.norm(Quat.mul(wq[p], lq[b]))
            wt[b] = wt[p] + Quat.rotate(wq[p], lt[b])
        }
    }

    /// Analytic 2-bone IK: a → b → c (c's origin is the end joint) to `target` (model space), bending toward the
    /// plane of the current pose; `endRot` (model space) for c. Returns the end's miss (m).
    @discardableResult
    private func twoBone(_ a: Int, _ b: Int, _ c: Int, _ target: F3, endRot: Q?, weight: Float) -> Float {
        if weight <= 1e-3 { return 0 }
        let A = wt[a], B = wt[b], C = wt[c]
        let T = C + (target - C) * min(1, weight)
        let l1 = len3(B - A), l2 = len3(C - B)
        let v = T - A
        let d0 = len3(v)
        let d = min(max(d0, abs(l1 - l2) + 1e-4), l1 + l2 - 1e-4)
        let dir = v / max(d0, 1e-6)
        let ca = min(1, max(-1, (l1 * l1 + d * d - l2 * l2) / (2 * l1 * d)))
        // bend plane from the current pose (the clip's elbow / knee)
        let mid = (A + C) * 0.5
        var pv = B - mid
        if len3(pv) < 1e-4 { pv = B - A }
        var perp = pv - dir * (pv * dir).sum()
        if len3(perp) < 1e-6 { perp = Mat4.cross(dir, F3(1, 0, 0)) }
        perp = unit3(perp)
        let Bn = A + dir * (l1 * ca) + perp * (l1 * (1 - ca * ca).squareRoot())
        let Cn = A + dir * d
        // upper bone: shortest arc onto the new elbow, then the twist that keeps the bend plane
        var q1 = Quat.between(B - A, Bn - A)
        let nOld = Quat.rotate(q1, Mat4.cross(B - A, C - B))
        let nNew = Mat4.cross(Bn - A, Cn - Bn)
        let ax = unit3(Bn - A)
        let u = nOld - ax * (nOld * ax).sum(), w = nNew - ax * (nNew * ax).sum()
        if len3(u) > 1e-6 && len3(w) > 1e-6 {
            let uu = unit3(u), ww = unit3(w)
            let ang = atan2f((Mat4.cross(uu, ww) * ax).sum(), (uu * ww).sum())
            q1 = Quat.mul(Quat.axis(ax, ang), q1)
        }
        let endWorld = wq[c]
        setWorld(a, Quat.norm(Quat.mul(q1, wq[a])))
        fkFrom(a)
        let q2 = Quat.between(wt[c] - wt[b], Cn - wt[b])
        setWorld(b, Quat.norm(Quat.mul(q2, wq[b])))
        fkFrom(b)
        if let r = endRot {
            setWorld(c, Quat.nlerp(endWorld, r, min(1, weight)))
        } else {
            setWorld(c, endWorld)
        }
        fkFrom(c)
        return d0 > l1 + l2 - 1e-4 ? d0 - (l1 + l2) : len3(wt[c] - T)
    }

    /// A socket's model-space position on the current pose.
    @inline(__always) private func socket(_ s: MarineAsset.Socket) -> F3 { wt[s.bone] + Quat.rotate(wq[s.bone], s.offset) }

    // ---------------------------------------------------------------- the split
    /// The turn clip's pelvis yaw progress at t (rad).
    private func turnYaw(_ side: Int, _ t: Float) -> Float {
        let tab = turnYawTab[side]
        guard tab.count > 1 else { return 0 }
        let p = min(max(0, t * asset.fps), Float(tab.count - 1))
        let f0 = min(Int(p), tab.count - 2)
        return tab[f0] + (tab[f0 + 1] - tab[f0]) * (p - Float(f0))
    }

    private func startTurn(_ side: Int, urgency: Float) {
        turnSide = side
        turnT = 0
        turnW = 0
        // the mocap turn steps round over 1.5–1.7 s; the game plays it brisker, faster still for a big swing
        turnRate = (1.25 + 0.45 * urgency) * tempo
        turnCount += 1
    }

    /// The turn is over (or interrupted): the legs' frame takes the clip's progress, the last animation pose is kept as a
    /// snapshot re-expressed in the new frame and faded out — no pop.
    private func endTurn() {
        let y = turnYawApplied
        feetYaw = wrapPi(feetYaw + y)
        let r = Quat.axis(F3(0, 1, 0), -y)
        for b in 0..<n { snapQ[b] = animQ[b]; snapT[b] = animT[b] }
        snapQ[asset.iPelvis] = Quat.norm(Quat.mul(r, animQ[asset.iPelvis]))
        snapT[asset.iPelvis] = Quat.rotate(r, animT[asset.iPelvis])
        snapW = 1
        turnSide = 0
        turnW = 0
        turnYawApplied = 0
    }

    /// The legs' yaw for this frame: moving, they follow the aim (the spine leads, the hips catch up); standing, they hold
    /// until the twist passes ±70° (a turn on the spot) or a smaller twist is held a while (a foot shuffle); the twist
    /// never exceeds ±110°.
    private func updateLegs(_ I: RigInput, dt: Float, fullBody: Bool) {
        let aim = I.yaw
        if !feetInit { feetYaw = aim; feetInit = true }
        let sp = (I.vel.x * I.vel.x + I.vel.y * I.vel.y).squareRoot()
        let moving = min(1, max(0, (sp - 0.15) / 0.6))
        if fullBody {
            if turnSide != 0 { endTurn() }
            feetYaw = aim
            settleClock = 0; shuffling = false
        } else if moving > 0.02 {
            if turnSide != 0 { endTurn() }
            let d = wrapPi(aim - feetYaw)
            feetYaw = wrapPi(feetYaw + d * min(1, dt * (5 + 7 * moving)))
            settleClock = 0; shuffling = false
        } else if turnSide != 0 {
            let s = turnSide > 0 ? 0 : 1
            let dur = asset.clips[iTurn[s]].duration
            turnT += dt * turnRate
            // the aim came back past the legs: no need to finish the step round
            let need = wrapPi(aim - feetYaw) - turnYaw(s, turnT)
            if turnT >= dur || (need * Float(turnSide) < -0.6 && turnT > 0.35 * dur) { endTurn() }
        } else {
            let d = wrapPi(aim - feetYaw)
            if abs(d) > MarineRig.twistSoft && iTurn[d > 0 ? 0 : 1] >= 0 {
                startTurn(d > 0 ? 1 : -1, urgency: min(1, (abs(d) - MarineRig.twistSoft) / 0.7))
                settleClock = 0; shuffling = false
            } else {
                settleClock = abs(d) > MarineRig.settleTwist ? settleClock + dt : 0
                if settleClock > MarineRig.settleAfter && !shuffling { shuffling = true; turnCount += 1 }
                if shuffling {
                    let st = min(abs(d), 2.0 * tempo * dt)
                    feetYaw = wrapPi(feetYaw + (d > 0 ? st : -st))
                    if abs(wrapPi(aim - feetYaw)) < 0.06 { shuffling = false; settleClock = 0 }
                }
            }
        }
        // the turn clip blends in over 0.18 s; the spine carries what the legs have not turned yet
        if turnSide != 0 {
            turnW = min(1, turnW + dt / 0.18)
            turnYawApplied = turnYaw(turnSide > 0 ? 0 : 1, turnT) * smooth01(turnW)
        } else {
            turnYawApplied = 0
        }
        var tw = wrapPi(aim - feetYaw) - turnYawApplied
        if tw > MarineRig.twistHard { feetYaw = wrapPi(feetYaw + tw - MarineRig.twistHard); tw = MarineRig.twistHard }
        if tw < -MarineRig.twistHard { feetYaw = wrapPi(feetYaw + tw + MarineRig.twistHard); tw = -MarineRig.twistHard }
        twist = fullBody ? 0 : tw
        twistMax = max(twistMax, abs(twist))
    }

    // ---------------------------------------------------------------- springs
    /// One spring tip step (world space, semi-implicit Euler; two substeps below 45 frames/s): the tip chases where the bone puts it,
    /// damped against the target's own motion (steady running leaves no offset; the antenna's air drag does); returns
    /// the world rotation taking the target direction onto the tip's, clamped.
    private func stepSpring(_ s: inout Spring, origin O: F3, target T: F3, dt: Float) -> Q? {
        if !s.on || dt <= 0 {
            s.p = T; s.v = .zero; s.tPrev = T; s.on = true
            return nil
        }
        let vT = (T - s.tPrev) / dt
        s.tPrev = T
        let w = 2 * Float.pi * s.freq * tempo
        let steps = dt > 1 / 45 ? 2 : 1
        let h = dt / Float(steps)
        for _ in 0..<steps {
            let a = (T - s.p) * (w * w) - (s.v - vT) * (2 * s.zeta * w) - s.v * s.drag
            s.v += a * h
            s.p += s.v * h
        }
        let L = len3(T - O)
        if L < 1e-4 { return nil }
        let t0 = (T - O) / L
        var t1 = unit3(s.p - O)
        let c = min(1, max(-1, (t0 * t1).sum()))
        if acosf(c) > s.maxAng {
            let ax = Mat4.cross(t0, t1)
            if len3(ax) > 1e-6 { t1 = Quat.rotate(Quat.axis(unit3(ax), s.maxAng), t0) }
            s.v *= 0.6
        }
        s.p = O + t1 * L
        return Quat.between(t0, t1)
    }

    /// World → model rotation (the instance yaw taken out).
    @inline(__always) private func toModel(_ q: Q) -> Q {
        Quat.norm(Quat.mul(Quat.mul(Quat.conj(yawQ), q), yawQ))
    }

    @inline(__always) private func worldPoint(_ p: F3) -> F3 {
        origin + Quat.rotate(yawQ, p)
    }

    // ---------------------------------------------------------------- actions (feel build A3)
    /// A clip's own travel at t (model xz: the pelvis from its first frame).
    private func clipDrift(_ c: Int, _ t: Float) -> SIMD2<Float> {
        let C = asset.clips[c]
        let f = C.loop ? 0 : min(C.frames - 1, max(0, Int(t * asset.fps)))
        let a = asset.pos[C.first * n + asset.iPelvis], b = asset.pos[(C.first + f) * n + asset.iPelvis]
        return SIMD2<Float>(b.x - a.x, b.z - a.z)
    }

    /// How far a clip's pelvis heading turns from its first frame to t (rad; an upright end).
    private func clipYaw(_ c: Int, _ t: Float) -> Float {
        let C = asset.clips[c]
        let f = min(C.frames - 1, max(0, Int(t * asset.fps)))
        func h(_ k: Int) -> Float {
            let z = Quat.rotate(Quat.norm(asset.rot[(C.first + k) * n + asset.iPelvis]), F3(1, 0, 0))
            return atan2f(-z.z, z.x)
        }
        return wrapPi(h(f) - h(0))
    }

    /// Turn the legs' frame by d (rad) without a pop: the last animation pose, re-expressed in the new frame, is
    /// faded out over 0.3 s (as a turn on the spot ends).
    private func reframe(_ d: Float) {
        if abs(d) < 1e-3 { return }
        if turnSide != 0 { endTurn() }
        feetYaw = wrapPi(feetYaw + d)
        let r = Quat.axis(F3(0, 1, 0), -d)
        for b in 0..<n { snapQ[b] = animQ[b]; snapT[b] = animT[b] }
        snapQ[asset.iPelvis] = Quat.norm(Quat.mul(r, animQ[asset.iPelvis]))
        snapT[asset.iPelvis] = Quat.rotate(r, animT[asset.iPelvis])
        snapW = 1
    }

    /// Start a full-body action (clip c), faced `face` (world yaw; nil = as the legs stand).
    private func startAct(_ k: ActKind, _ c: Int, rate: Float = 1, face: Float? = nil, loop: (Float, Float)? = nil) {
        if c < 0 { return }
        if act >= 0 { endAct(now: true) }
        if let f = face { reframe(wrapPi(f - feetYaw)) }
        actKind = k; act = c; actT = 0; actRate = rate; actEnding = false; actLoop = loop
        actShift = .zero
        actRot = 0
        if !actMasked { lockOn = [false, false] }
        actionCount += 1
    }

    /// The action ends: its travel goes into the visual offset (and out of the clip while it fades), its last heading
    /// into the legs' frame.
    private func endAct(now: Bool = false) {
        guard act >= 0, !actEnding else { if now { act = -1; actKind = .none; actW = 0 }; return }
        let d = clipDrift(act, actT)
        rootOff += Quat.rotate(yawQ, F3(d.x, 0, d.y))
        actShift = d
        if (actKind == .stagger || actKind == .knock) && !actMasked {
            actRot = clipYaw(act, actT)
            reframe(actRot)
        }
        actEnding = true
        if now { act = -1; actKind = .none; actW = 0 }
    }

    /// The full-body actions of a marine on its feet: triggers (a heavy hit, standing by a squadmate being revived, the
    /// rising lift), the clock and the fades; samples the clip into the override accumulator. Returns its weight.
    private func fullBodyAction(_ I: RigInput, heavy: SIMD2<Float>?, speed sp: Float, dt: Float) -> Float {
        if let k = heavy, actKind != .knock {
            let fwd = SIMD2<Float>(sinf(feetYaw), cosf(feetYaw))
            let along = (k * fwd).sum()                      // > 0: shoved from behind
            let km = (I.knock * I.knock).sum().squareRoot()
            let hard = km >= 11 && iKnock >= 0 && sp < 3 && along <= 0.35
            actMasked = !hard && sp > 1.2                     // running: the stagger is the upper body's, the legs run on
            if along > 0.35 && iStaggerB >= 0 {
                startAct(.stagger, iStaggerB, face: actMasked ? nil : atan2f(k.x, k.y))
            } else if hard {
                startAct(.knock, iKnock, face: atan2f(-k.x, -k.y))
            } else if iStaggerF >= 0 {
                startAct(.stagger, iStaggerF, face: actMasked ? nil : atan2f(-k.x, -k.y))
            }
        }
        // by a downed squadmate whose revive the core is counting: kneel facing him, a little closer
        if let h = I.help, iHelp >= 0, sp < 0.4, act < 0 || (actKind == .brace) {
            let d = h - SIMD2<Float>(I.pos.x, I.pos.z)
            actMasked = false
            startAct(.help, iHelp, face: atan2f(d.x, d.y), loop: MarineRig.helpLoop)
            let L = (d * d).sum().squareRoot()
            let step = max(0, min(0.8, L - 0.95))
            helpOff = L > 1e-3 ? F3(d.x, 0, d.y) / L * step : .zero
        }
        if actKind == .help && !actEnding && actLoop != nil && (I.help == nil || sp > 0.5) {
            actLoop = nil                                     // done (or off he goes): rise, played out from the loop's end
            if actT < MarineRig.helpLoop.1 { actT = MarineRig.helpLoop.1 }
            if sp > 0.5 { actRate = 2.4 }
        }
        // (only while not firing: the brace holds the weapon low — a marine shooting off the lift keeps its aim)
        if I.brace && !I.firing && iBrace >= 0 && sp < 0.4 && act < 0 {
            actMasked = false
            startAct(.brace, iBrace)
        }
        if actKind == .brace && !actEnding && (!I.brace || I.firing || sp > 0.6) { endAct() }
        guard act >= 0 else { return 0 }
        let C = asset.clips[act]
        var r = actRate * tempo
        if actKind == .knock && sp > 1.5 { r *= 1.7 }       // the simulation is moving him: up quicker
        actT += dt * r
        if let L = actLoop, actT > L.1 { actT = L.0 + (actT - L.1) }
        if !C.loop && !actEnding && actT >= C.duration - 0.22 { endAct() }
        let fadeIn: Float = actKind == .help || actKind == .brace ? 0.3 : 0.07
        actW = actEnding ? max(0, actW - dt / 0.22) : min(1, actW + dt / fadeIn)
        // kneeling: the body closes the last stretch to the squadmate (the visual offset), back once it has risen
        if actKind == .help && !actEnding {
            let goal = helpOff * smooth01(actT / 0.6)
            rootOff += goal - helpCur
            helpCur = goal
        } else {
            helpCur = .zero                                   // (what it moved eases back with the offset once he stands)
        }
        if actEnding && actW <= 0 { act = -1; actKind = .none; return 0 }
        if actMasked { state = "stagger"; return 0 }
        acc(act, time: C.loop ? actT : min(actT, C.duration - 1e-3), max(1e-3, actW), shift: actShift, rot: actRot)
        switch actKind {
        case .stagger: state = "stagger"
        case .knock: state = "knockdown"
        case .help: state = "help"
        case .brace: state = "brace"
        case .none: break
        }
        return actW
    }

    /// The upper-body actions (the cast, the weapon action, the victory; a stagger on the run) through the bone mask:
    /// spine1 at 45 %, spine2 at 80 %, chest, head, arms, the weapon and the armour on them fully; the hands' IK
    /// weights follow the clip's (the support hand leaves the grip to throw, reload, gesture).
    private func upperBodyActions(_ I: RigInput, ctrl: inout SIMD4<Float>, dt: Float) {
        if !seqInit { seqInit = true; lastCast = I.castSeq; lastWeapon = I.weaponSeq }
        let free = !I.downed && I.clip == nil && (overrideW < 0.5 || actKind == .brace)
        if I.castSeq != lastCast {
            lastCast = I.castSeq
            if free && iCast >= 0 { up = iCast; upT = MarineRig.castStart; upHold = false; upW = min(upW, 0.3); actionCount += 1 }
        }
        if I.weaponSeq != lastWeapon {
            lastWeapon = I.weaponSeq
            if free && iWeaponAct >= 0 && up != iCast { up = iWeaponAct; upT = 0; upHold = false; actionCount += 1 }
        }
        if I.victory && !wasVictory && iVictory >= 0 && !I.downed { up = iVictory; upT = 0; upHold = true; actionCount += 1 }
        wasVictory = I.victory
        if up == iVictory && !I.victory { upHold = false }
        if up >= 0 {
            let dur = asset.clips[up].duration
            upT += dt * tempo
            let done = !upHold && upT >= dur - 0.2
            upW = done || !free ? max(0, upW - dt / 0.22) : min(1, upW + dt / 0.08)
            if upW <= 0 && (done || !free) { up = -1 } else {
                maskBlend(up, min(upT, dur - 1e-3), upW, ctrl: &ctrl)
                if up == iCast { state = "cast" } else if up == iVictory { state = "victory" } else { state = asset.cls == .assault ? "reload" : "vent" }
            }
        }
        if act >= 0 && actMasked && actW > 1e-3 {
            maskBlend(act, min(actT, asset.clips[act].duration - 1e-3), actW * 0.85, ctrl: &ctrl)
        }
    }

    private func maskBlend(_ c: Int, _ t: Float, _ w: Float, ctrl: inout SIMD4<Float>) {
        beginAcc()
        acc(c, time: t, 1)
        let uc = ctrlAcc
        endAcc(into: &oq, &ot)
        let k = smooth01(w)
        for (b, m) in upMask {
            let wb = k * m
            lq[b] = Quat.nlerp(lq[b], oq[b], wb)
            lt[b] += (ot[b] - lt[b]) * wb
        }
        ctrl.x += (uc.x - ctrl.x) * k
        ctrl.y += (uc.y - ctrl.y) * k
    }

    // ---------------------------------------------------------------- the frame
    /// Advance and pose this marine for the frame (world space input), dt seconds since the last drawn frame.
    func update(_ I0: RigInput, dt dt0: Float) {
        let dt = min(0.1, max(0, dt0))
        let simPos = I0.pos
        // a jump in position (lift, spawn, revive warp): no lock or spring survives it
        var jumped = false
        if hasPrev {
            let j = simPos - prevPos
            if (j.x * j.x + j.z * j.z) > 0.8 * 0.8 { jumped = true }
        }
        if jumped { rootOff = .zero }
        // the body stands where the simulation has the marine plus the travel of its last full-body clips (A3)
        var I = I0
        I.pos = simPos + rootOff
        origin = I.pos
        let fullBody = I.downed || I.clip != nil || overrideW > 0.5 || dashClock < 10 || getUpClock < 10 || (act >= 0 && actW > 0.5 && !actMasked)
        updateLegs(I, dt: dt, fullBody: fullBody)
        yaw = feetYaw
        yawQ = Quat.axis(F3(0, 1, 0), yaw)
        world = Mat4.translation(I.pos.x, I.pos.y, I.pos.z) * Mat4.rotationY(yaw)
        // velocity in the legs' frame (+z = the legs' facing, +x = the marine's left)
        let c = cosf(yaw), s = sinf(yaw)
        let lx = I.vel.x * c - I.vel.y * s, lz = I.vel.x * s + I.vel.y * c
        let sp = (lx * lx + lz * lz).squareRoot()
        speedSm += (sp - speedSm) * min(1, dt * 10)
        if sp > 0.2 {
            let d = SIMD2<Float>(lx, lz) / sp
            dirSm += (d - dirSm) * min(1, dt * 12)
        }
        let dlen = (dirSm * dirSm).sum().squareRoot()
        let dir = dlen > 1e-4 ? dirSm / dlen : SIMD2<Float>(0, 1)
        // ---- base: locomotion
        let v = speedSm
        let walkV = asset.clips[iDirs[0][0]].stride / max(1e-3, asset.clips[iDirs[0][0]].duration)
        let runV = asset.clips[iDirs[1][0]].stride / max(1e-3, asset.clips[iDirs[1][0]].duration)
        let wRun = min(1, max(0, (v - walkV) / max(0.1, runV - walkV)))
        gaitRun += (wRun - gaitRun) * min(1, dt * 8)
        let moveW = min(1, max(0, (v - 0.08) / 0.7))
        // 8-way: the angle of the movement relative to the legs (0 = forward, +90 = toward the marine's left)
        var ang = atan2f(dir.x, dir.y) * 180 / Float.pi
        if ang < 0 { ang += 360 }
        let sect = ang / 45
        let i0 = Int(sect) % 8, i1 = (i0 + 1) % 8
        let fa = sect - floorf(sect)
        // each direction's loop has its own stride (a side step or a back-pedal is shorter than a forward stride, A1):
        // the phase runs on the stride of the two directions being blended
        let C = asset.clips
        let strideW = C[iDirs[0][i0]].stride * (1 - fa) + C[iDirs[0][i1]].stride * fa
        let strideR = C[iDirs[1][i0]].stride * (1 - fa) + C[iDirs[1][i1]].stride * fa
        let stride = strideW + (strideR - strideW) * gaitRun
        // the phase runs on the distance actually covered this frame (raw speed: a smoothed one lags the body when it
        // speeds up, and the planted foot would be dragged); each marine starts at its own phase
        phase += sp * dt / max(0.2, stride)
        phase -= floorf(phase)
        idleClock += dt * tempo
        beginAcc()
        acc(iIdle, time: idleClock, 1 - moveW)
        if moveW > 1e-3 {
            for (g, gw) in [(0, 1 - gaitRun), (1, gaitRun)] where gw > 1e-3 {
                accPhase(iDirs[g][i0], phase, moveW * gw * (1 - fa))
                accPhase(iDirs[g][i1], phase, moveW * gw * fa)
            }
        }
        endAcc(into: &lq, &lt)
        var ctrl = ctrlAcc / max(1e-6, accW)
        var vis = ctrlVisor / max(1e-6, accW)
        state = moveW < 0.5 ? (shuffling ? "shuffle" : "idle") : (gaitRun > 0.5 ? "run" : "walk")
        // ---- the turn on the spot (legs and hips from the clip; the spine's twist keeps the chest on the aim)
        if turnSide != 0 {
            let side = turnSide > 0 ? 0 : 1
            let ci = iTurn[side]
            let dur = asset.clips[ci].duration
            let t = min(turnT, dur - 1e-3)
            beginAcc()
            acc(ci, time: t, 1)
            let tc = ctrlAcc / max(1e-6, accW), tv = ctrlVisor / max(1e-6, accW)
            endAcc(into: &oq, &ot)
            let e = smooth01(t / dur)
            ot[asset.iPelvis].x -= turnDrift[side].x * e
            ot[asset.iPelvis].z -= turnDrift[side].z * e
            let w = smooth01(turnW)
            for b in 0..<n where b != asset.iCtrl {
                lq[b] = Quat.nlerp(lq[b], oq[b], w)
                lt[b] += (ot[b] - lt[b]) * w
            }
            ctrl += (tc - ctrl) * w
            vis += (tv - vis) * w
            state = "turn"
        }
        // ---- the snapshot of a finished turn, fading out
        if snapW > 0 {
            let w = smooth01(snapW)
            for b in 0..<n where b != asset.iCtrl {
                lq[b] = Quat.nlerp(lq[b], snapQ[b], w)
                lt[b] += (snapT[b] - lt[b]) * w
            }
            snapW = max(0, snapW - dt / 0.3)
        }
        // ---- full-body overrides
        var want: Float = 0
        // a heavy hit (a boomer, a brute's ram: the core's knockback ≥ 6.5 m/s) on a marine on its feet (A3): a stagger,
        // or the knock-down when it is thrown back hard
        var heavy: SIMD2<Float>? = nil
        if I.hurtT > prevHurt + 0.05 && !I.downed && I.clip == nil {
            let km = (I.knock * I.knock).sum().squareRoot()
            if km >= 6.5 { heavy = I.knock / km }
        }
        beginAcc()
        if I.downed {
            if !wasDowned {
                downClock = 0; deathClock = 0; deathStand = false; downShift = .zero; downMoved = false
                if act >= 0 { endAct(now: true) }
                up = -1; upW = 0
            }
            downClock += dt
            let dd = asset.clips[iDown].duration
            let xf: Float = 0.4                      // the fall crossfades into lying for its last 0.4 s
            if !downMoved && !deathStand && downClock >= dd - xf {
                // the fall's travel moves into the visual offset (the lying clips start over their own origin)
                downMoved = true
                let d = clipDrift(iDown, dd)
                rootOff += Quat.rotate(yawQ, F3(d.x, 0, d.y))
                downShift = d
            }
            let wLie = downClock < dd - xf ? 0 : smooth01((downClock - (dd - xf)) / xf)
            if I.dead {
                if deathClock == 0 { deathStand = downClock < 0.7 && iDeathStand >= 0 }
                deathClock += dt
                if deathStand {
                    // the last one down falls dead: the standing death takes over the fall
                    let w = smooth01(deathClock / 0.25)
                    acc(iDown, time: downClock, 1 - w, shift: downShift)
                    acc(iDeathStand, time: downClock, w)
                } else {
                    let w = smooth01(deathClock / 0.35)
                    if wLie < 1 { acc(iDown, time: downClock, (1 - wLie) * (1 - w), shift: downShift) }
                    acc(iDowned, time: max(0, downClock - dd), wLie * (1 - w))
                    acc(iDeath, time: deathClock, w)
                }
                state = "death"
            } else {
                let rv = min(1, max(0, I.revive))
                reviveW += ((rv > 0.01 ? 1 : 0) - reviveW) * min(1, dt * 6)
                let wl = 1 - reviveW
                if wLie < 1 { acc(iDown, time: downClock, wl * (1 - wLie), shift: downShift) }
                if wLie > 0 { acc(iDowned, time: max(0, downClock - (dd - xf)), wl * wLie) }
                state = downClock < dd ? "down" : "downed"
                if reviveW > 1e-3 {
                    acc(iRevive, time: rv * MarineRig.reviveScrub * asset.clips[iRevive].duration, reviveW)
                    state = "revive"
                }
                getUpFrom = rv * MarineRig.reviveScrub
            }
            want = 1
            overrideW = 1
            getUpClock = 10
        } else if let name = I.clip, let ci = asset.clipIndex[name] {
            acc(ci, time: I.clipTime, 1)
            want = 1
            state = name
        } else {
            if wasDowned {
                getUpClock = 0
                getUpShift = .zero
                lockOn = [false, false]
            }
            let rd = asset.clips[iRevive].duration
            if getUpClock < 10 {
                getUpClock += dt
                let t = getUpFrom * rd + getUpClock
                if t >= rd && getUpShift == .zero {
                    // on its feet: the get-up's travel into the visual offset, its heading into the legs
                    let d = clipDrift(iRevive, rd)
                    rootOff += Quat.rotate(yawQ, F3(d.x, 0, d.y))
                    getUpShift = d + SIMD2<Float>(1e-6, 0)
                    getUpRot = clipYaw(iRevive, rd)
                    reframe(getUpRot)
                }
                acc(iRevive, time: t, 1, shift: getUpShift, rot: t >= rd ? getUpRot : 0)
                state = "getup"
                want = t < rd ? 1 : max(0, 1 - (t - rd) / 0.25)
                if t > rd + 0.25 { getUpClock = 10 }
            }
            // dash: rising edge of the core's dash timer
            if I.dashT > 0 && prevDash <= 0 {
                dashClock = 0
                let dx = I.dashDir.x * c - I.dashDir.y * s, dz = I.dashDir.x * s + I.dashDir.y * c
                dashRel = SIMD2<Float>(dx, dz)
                lockOn = [false, false]
                fatigue = min(1, fatigue + 0.1)
                if act >= 0 { endAct(now: true) }
            }
            if dashClock < 10 && want < 0.5 {
                dashClock += dt
                // f l b r at 0 / 90 / 180 / 270
                var a = atan2f(dashRel.x, dashRel.y) * 180 / Float.pi
                if a < 0 { a += 360 }
                let q = a / 90
                let j0 = Int(q) % 4, j1 = (j0 + 1) % 4
                let f = q - floorf(q)
                acc(iDash[j0], time: dashClock, 1 - f)
                acc(iDash[j1], time: dashClock, f)
                let dur = asset.clips[iDash[0]].duration
                want = dashClock < 0.3 ? 1 : max(0, 1 - (dashClock - 0.3) / max(0.05, dur - 0.3))
                if dashClock > dur { dashClock = 10 }
                state = "dash"
            }
            if want < 0.5 { want = max(want, fullBodyAction(I, heavy: heavy, speed: sp, dt: dt)) }
        }
        prevDash = I.dashT
        if accW > 1e-4 {
            let oc = ctrlAcc / accW, ov = ctrlVisor / accW
            endAcc(into: &oq, &ot)
            overrideW = I.downed ? 1 : want
            let w = overrideW
            for b in 0..<n where b != asset.iCtrl {
                lq[b] = Quat.nlerp(lq[b], oq[b], w)
                lt[b] += (ot[b] - lt[b]) * w
            }
            ctrl += (oc - ctrl) * w
            vis += (ov - vis) * w
        } else {
            overrideW = 0
        }
        wasDowned = I.downed
        // ---- upper-body actions through the bone mask (A3): the cast, the weapon action, the victory; a stagger while
        // the marine runs plays here too (the legs keep running)
        upperBodyActions(I, ctrl: &ctrl, dt: dt)
        // the visual offset eases back once the marine stands on its own (the planted feet re-step after it)
        if act < 0 && !I.downed && getUpClock >= 10 && overrideW < 0.5 {
            let l = (rootOff * rootOff).sum().squareRoot()
            if l > 1e-4 { rootOff *= max(0, l - dt * (0.6 + 0.8 * min(1, sp))) / l }
            if l > 1.5 { rootOff *= 1.5 / l }
        }
        // the animation pose of this frame (a turn's end and a reframed action crossfade from it)
        for b in 0..<n { animQ[b] = lq[b]; animT[b] = lt[b] }
        let upright = 1 - overrideW
        // ---- additive layers: the per-weapon recoil
        if !I.downed {
            switch asset.cls {
            case .assault:
                if I.muzzle > prevMuzzle + 0.3 { fireClock = 0 }
                fireClock += dt
                additive(iFire, time: fireClock, fireClock < 0.25 ? 1 : 0)
            default:
                let want: Float = I.firing ? (asset.cls == .gunner ? I.spin : 1) : 0
                fireLoopW += (want - fireLoopW) * min(1, dt * 10)
                fireLoopT += dt
                additive(iFire, time: fireLoopT, fireLoopW)
            }
        }
        prevMuzzle = I.muzzle
        // ---- hit reactions: a directional impulse up the spine, each bone a beat later; heavy hits shove the hips
        if I.hurtT > prevHurt + 0.05 && !I.downed {
            let kx = I.knock.x * c - I.knock.y * s, kz = I.knock.x * s + I.knock.y * c
            let km = (kx * kx + kz * kz).squareRoot()
            // the push's direction (model frame); acid (no knock) reads as a hit from the front of the aim
            hitDir = km > 0.05 ? SIMD2<Float>(kx, kz) / km : SIMD2<Float>(-sinf(twist), -cosf(twist))
            // a bite (knock 0.6) ≈ 0.38, a boomer (7) ≈ 1.3, a brute's ram (13) 1.5
            hitMag = min(1.5, 0.3 + km / 7)
            hitClock = 0
            hitFired = 0
            hitCount += 1
        }
        prevHurt = I.hurtT
        hitClock += dt
        let hw = 2 * Float.pi * 2.3 * tempo, hz: Float = 0.3
        let gains = MarineRig.hitGain
        // at rest (every impulse fired, the chain settled): nothing to integrate
        if hitFired == 31 && hitClock > 2.5 {
            for i in 0..<5 where (hitTilt[i] * hitTilt[i]).sum() > 0 { hitTilt[i] = .zero; hitVel[i] = .zero }
        } else {
        for i in 0..<5 {
            if hitFired & (1 << i) == 0 && hitClock >= Float(i) * 0.035 / tempo {
                hitFired |= 1 << i
                if hitClock < 1 { hitVel[i] += hitDir * (2.7 * hitMag * gains[i]) }
                if i == 0 && hitClock < 1 {
                    shoveV += F3(hitDir.x, 0, hitDir.y) * (0.55 * hitMag) + F3(0, -0.45 * max(0, hitMag - 0.5), 0)
                }
            }
            let steps = dt > 1 / 45 ? 2 : 1
            let h = dt / Float(steps)
            for _ in 0..<steps {
                hitVel[i] += (-hitTilt[i] * (hw * hw) - hitVel[i] * (2 * hz * hw)) * h
                hitTilt[i] += hitVel[i] * h
            }
            let l = (hitTilt[i] * hitTilt[i]).sum().squareRoot()
            if l > 0.45 { hitTilt[i] *= 0.45 / l }
        }
        }
        if hitClock < 3 {
            let w = 2 * Float.pi * 2.0, z: Float = 0.55
            let steps = dt > 1 / 45 ? 2 : 1
            let h = dt / Float(steps)
            for _ in 0..<steps {
                shoveV += (-shoveP * (w * w) - shoveV * (2 * z * w)) * h
                shoveP += shoveV * h
            }
        } else if shoveP.x != 0 || shoveP.y != 0 || shoveP.z != 0 {
            shoveP = .zero; shoveV = .zero
        }
        if I.downed { for i in 0..<5 { hitTilt[i] = .zero; hitVel[i] = .zero }; shoveP = .zero; shoveV = .zero }
        // ---- breathing / fatigue: a per-marine rate, faster and deeper when hurt or blown after a sprint
        hurtSm += ((1 - min(1, max(0, I.hp))) - hurtSm) * min(1, dt * 0.8)
        let runK = gaitRun * moveW * upright
        fatigue = min(1, max(0, fatigue + dt * 0.085 * runK - dt * 0.03 * (1 - runK)))
        let rate = 0.24 * tempo * (1 + 1.1 * fatigue + 0.8 * hurtSm)
        breathPh += dt * rate
        breathPh -= floorf(breathPh)
        // inhale over 40 % of the breath, a longer exhale
        let bx = breathPh
        let breath = bx < 0.4 ? smooth01(bx / 0.4) : 1 - smooth01((bx - 0.4) / 0.6)
        let bAmp = (1 + 1.6 * fatigue + 0.9 * hurtSm) * (1 - 0.5 * moveW) * upright
        let deg = Float.pi / 180
        let bPitch = -breath * bAmp * deg            // the chest lifts (leans back a touch) on the inhale
        let hunch = fatigue * fatigue * (1 - moveW) * upright * 4 * deg   // blown: bent over a little, catching breath
        // ---- head look-at: the nearest threat within ±60° of the aim and −12…+28° of pitch, else the aim
        var ly: Float = 0, lp: Float = 0
        if let L = I.look, upright > 0.5 {
            let r = Quat.rotate(Quat.axis(F3(0, 1, 0), -yaw), L - I.pos)
            let hd = (r.x * r.x + r.z * r.z).squareRoot()
            if hd > 0.5 {
                ly = min(1.05, max(-1.05, wrapPi(atan2f(r.x, r.z) - twist)))
                lp = min(0.49, max(-0.21, atan2f(1.6 - r.y, hd) - 0.12))
            }
        }
        lookYaw += (ly - lookYaw) * min(1, dt * 7)
        lookPitch += (lp - lookPitch) * min(1, dt * 6)
        // ---- the spine chain: twist (pelvis → chest), look (neck, head), hit tilt, breath — each a model-space rotation
        // applied in its parent's frame of the animation pose, so the children inherit it (one FK pass after)
        do {
            let up = F3(0, 1, 0)
            let lat = F3(cosf(twist), 0, -sinf(twist))        // the chest's left axis: pitch turns about it
            // root … head of the animation pose (model space): pelvis, spine1, spine2, chest, neck, head each the child of
            // the one before, the pelvis of the root
            chainW[0] = lq[0]
            for j in 0..<6 { chainW[j + 1] = Quat.norm(Quat.mul(chainW[j], lq[chainBones[j]])) }
            for j in 0..<6 {
                let b = chainBones[j]
                var D = Quat.identity
                if j < 4 { D = Quat.axis(up, twist * MarineRig.twistShare[j]) }
                if j >= 1 {
                    let i = j - 1
                    let t = hitTilt[i]
                    let tl = (t * t).sum().squareRoot()
                    if tl > 1e-5 { D = Quat.mul(Quat.axis(F3(t.y, 0, -t.x) / tl, tl * upright), D) }
                }
                var pitch: Float = 0
                switch j {
                case 1: pitch = hunch * 0.6
                case 2: pitch = bPitch * 0.45 + hunch * 0.4
                case 3: pitch = bPitch
                case 4: pitch = lookPitch * 0.35 - bPitch * 0.4 - hunch * 0.3
                case 5: pitch = lookPitch * 0.65 - bPitch * 0.5 - hunch * 0.5
                default: break
                }
                if j == 4 || j == 5 {
                    let k: Float = j == 4 ? 0.4 : 0.6
                    D = Quat.mul(Quat.axis(up, lookYaw * k * upright), D)
                }
                if pitch != 0 { D = Quat.mul(Quat.axis(lat, pitch), D) }
                let pw = chainW[j]                               // the parent's animation-pose rotation
                lq[b] = Quat.norm(Quat.mul(Quat.mul(Quat.mul(Quat.conj(pw), D), pw), lq[b]))
            }
            // shoulders rise on the inhale (clavicles roll about the chest's forward axis)
            let sh = breath * bAmp * 1.7 * deg
            lq[iClav.0] = Quat.norm(Quat.mul(Quat.axis(F3(0, 0, 1), sh), lq[iClav.0]))
            lq[iClav.1] = Quat.norm(Quat.mul(Quat.axis(F3(0, 0, 1), -sh), lq[iClav.1]))
            // the hips' shove and dip (heavy hits)
            lt[asset.iPelvis] += shoveP * upright
        }
        // ---- the spinning part of the weapon
        switch asset.cls {
        case .gunner: auxAngle += I.spin * dt * 40
        case .cryo: auxAngle += (I.firing ? 9 : 1.2) * dt
        default: break
        }
        auxAngle = fmodf(auxAngle, 2 * Float.pi)
        lq[asset.iAux] = Quat.norm(Quat.mul(lq[asset.iAux], Quat.axis(F3(0, 0, 1), auxAngle)))
        ikGun = min(1, max(0, ctrl.x)); ikSup = min(1, max(0, ctrl.y))
        plant = SIMD2<Float>(min(1, max(0, ctrl.z)), min(1, max(0, ctrl.w)))
        visor = min(1, max(0, vis))
        fk()
        if jumped {
            for i in 0..<springs.count { springs[i].on = false }
            gunSpring.on = false
        }
        // ---- the weapon lags the chest a beat (a spring on the chest's forward tip, applied to the gun): the hands follow
        if upright > 0.5 {
            let ch = asset.iChest
            let O = worldPoint(wt[ch]), T = worldPoint(wt[ch] + Quat.rotate(wq[ch], gunSpring.tip))
            if let q = stepSpring(&gunSpring, origin: O, target: T, dt: dt) {
                let wb = asset.iWeapon
                setWorld(wb, Quat.norm(Quat.mul(toModel(q), wq[wb])))
                fkOne(wb)
                fkOne(asset.iAux)
            }
        } else {
            gunSpring.on = false
        }
        // ---- hands on the grips
        let grips = MarineRig.grips, handAxes = MarineRig.handAxes
        for side in 0..<2 {
            let w = side == 0 ? ikGun : ikSup
            guard w > 1e-3, let g = asset.sockets[grips[side].0], let gy = asset.sockets[grips[side].1], let gz = asset.sockets[grips[side].2],
                  let hy = asset.sockets[handAxes[side].0], let hz = asset.sockets[handAxes[side].1] else { continue }
            let p = socket(g), py = socket(gy), pz = socket(gz)
            let z = unit3(pz - p)
            var y = py - p
            y = unit3(y - z * (y * z).sum())
            let x = Mat4.cross(y, z)
            // the hand's canonical frame at bind (bone-local offsets of its axis sockets)
            let bz = unit3(hz.offset)
            var by = hy.offset
            by = unit3(by - bz * (by * bz).sum())
            let bx = Mat4.cross(by, bz)
            let qF = Quat.fromAxes(x, y, z), qB = Quat.fromAxes(bx, by, bz)
            let rot = Quat.mul(qF, Quat.conj(qB))
            let (a, b, h) = asset.iArm[side]
            let err = twoBone(a, b, h, p, endRot: rot, weight: w)
            if w > 0.99 { gripErrMax = max(gripErrMax, err) }
        }
        // ---- feet: planted balls stay put in the world (leg IK); a turning idle marine re-steps
        let inv = Mat4.rotationY(-yaw)
        if jumped { lockOn = [false, false]; lastPlanted = [false, false]; slideAcc = [0, 0] }
        prevPos = simPos
        hasPrev = true
        // the planted targets of this frame (model space ball positions), and the pelvis drop that keeps them in reach
        var targets: [F3?] = [nil, nil]
        var drop: Float = 0
        for side in 0..<2 {
            let (th, sh, ft, toe) = asset.iLeg[side]
            let ballM = wt[toe]
            let ballW = I.pos + Quat.rotate(yawQ, ballM)
            // (a full-body action owns the feet from its first frame to its last: no lock drags them through its fades —
            // they lock afresh where it leaves them)
            let planted = plant[side] > 0.5 && overrideW < 0.5 && !I.treadmill && !(act >= 0 && !actMasked)
            if !planted {
                lockOn[side] = false
                continue
            }
            if !lockOn[side] {
                lockOn[side] = true
                lockPos[side] = F3(ballW.x, ballM.y + I.pos.y, ballW.z)
                stepClock[side] = 1
                slideAcc[side] = 0
            }
            // a re-step instead of a drag: too far from where the clip wants it (the legs' frame turned under a planted
            // foot: the settle shuffle steps one foot at a time, early), or the lock out of the leg's reach (a reversal,
            // a sharp turn, the walk ↔ run blend) — the foot lifts and steps to the clip's ball, it never slides
            let dx = lockPos[side] - F3(ballW.x, lockPos[side].y, ballW.z)
            if stepClock[side] >= 1 {
                let l4 = inv.point(lockPos[side].x - I.pos.x, lockPos[side].y - I.pos.y, lockPos[side].z - I.pos.z)
                let h0 = F3(l4.x, l4.y, l4.z) - Quat.rotate(wq[ft], lt[toe]) - wt[th]
                let r0 = (len3(wt[sh] - wt[th]) + len3(wt[ft] - wt[sh])) * 0.995
                let dxz = h0.x * h0.x + h0.z * h0.z
                let outOfReach = dxz >= r0 * r0 || (-h0.y) - (r0 * r0 - dxz).squareRoot() > 0.07
                let otherDown = stepClock[1 - side] >= 1
                let thr: Float = shuffling ? 0.07 : 0.32
                if (len3(dx) > thr && moveW < 0.3 && (otherDown || !shuffling)) || outOfReach {
                    stepFrom[side] = lockPos[side]
                    stepClock[side] = 0
                    stepDur[side] = moveW < 0.3 ? (shuffling ? 0.17 : 0.2) : 0.12
                    restepCount += 1
                }
            }
            var target = lockPos[side]
            if stepClock[side] < 1 {
                stepClock[side] = min(1, stepClock[side] + dt / stepDur[side])
                let e = stepClock[side] * stepClock[side] * (3 - 2 * stepClock[side])
                let goal = F3(ballW.x, lockPos[side].y, ballW.z)
                target = stepFrom[side] + (goal - stepFrom[side]) * e + F3(0, 0.09 * sinf(Float.pi * stepClock[side]), 0)
                if stepClock[side] >= 1 { lockPos[side] = goal }
            }
            let tm4 = inv.point(target.x - I.pos.x, target.y - I.pos.y, target.z - I.pos.z)
            let tm = F3(tm4.x, tm4.y, tm4.z)
            targets[side] = tm
            // the ankle the ball needs (through the foot's current rotation) vs the leg's reach from the hip
            let ankle = tm - Quat.rotate(wq[ft], lt[toe])
            let hip = wt[th]
            let reach = (len3(wt[sh] - hip) + len3(wt[ft] - wt[sh])) * 0.995
            let h = ankle - hip
            let dxz2 = h.x * h.x + h.z * h.z
            if dxz2 < reach * reach {
                let need = (-h.y) - (reach * reach - dxz2).squareRoot()   // > 0: the hip must come down this much
                drop = max(drop, need)
            } else {
                drop = max(drop, 0.07)
            }
        }
        // drop at once, ease back up (the "pelvis drop on contact" the stance needs), 7 cm at most
        pelvisDrop = min(0.07, max(drop, pelvisDrop - dt * 0.35))
        if pelvisDrop > 1e-4 {
            lt[asset.iPelvis].y -= pelvisDrop
            fkFrom(asset.iPelvis)
        }
        for side in 0..<2 {
            guard let tm = targets[side] else { lastPlanted[side] = false; continue }
            let (th, sh, ft, toe) = asset.iLeg[side]
            // world → model, ankle from the ball through the foot's current rotation; out of reach even so: the
            // lock gives way to the nearest reachable point (that is a slide, and it is counted)
            var ankle = tm - Quat.rotate(wq[ft], lt[toe])
            let hip = wt[th]
            let reach = (len3(wt[sh] - hip) + len3(wt[ft] - wt[sh])) * 0.999
            let h = ankle - hip
            if len3(h) > reach {
                ankle = hip + unit3(h) * reach
                let ball = ankle + Quat.rotate(wq[ft], lt[toe])
                let bw = I.pos + Quat.rotate(yawQ, ball)
                lockPos[side] = F3(bw.x, lockPos[side].y, bw.z)
            }
            twoBone(th, sh, ft, ankle, endRot: nil, weight: 1)
            // diagnostics: how far the planted ball moved in the world over this contact
            let now = I.pos + Quat.rotate(yawQ, wt[toe])
            if lastPlanted[side] && stepClock[side] >= 1 {
                let d = now - lastBall[side]
                slideAcc[side] += (d.x * d.x + d.z * d.z).squareRoot()
                slideMax = max(slideMax, slideAcc[side])
            }
            lastBall[side] = now
            lastPlanted[side] = stepClock[side] >= 1
        }
        // ---- secondary armour follows (after IK)
        for (dst, src, k, liftOnly) in asset.iFollow {
            let q = lq[src]
            if liftOnly {
                let fwd = Quat.rotate(q, F3(0, -1, 0))
                let lift = max(0, atan2f(fwd.z, -fwd.y))
                lq[dst] = Quat.axis(F3(1, 0, 0), -lift * k)
            } else {
                // the upper arm's swing away from its bind direction (no twist), a fraction of it
                let child = src + 1
                let d0 = asset.bindLocal[child]
                lq[dst] = Quat.nlerp(Quat.identity, Quat.between(d0, Quat.rotate(q, d0)), k)
            }
        }
        fk()
        // ---- springs: pauldrons, pack (then its antenna), tassets — each chases where the pose puts it and overshoots
        for i in 0..<springs.count {
            let b = springs[i].bone
            if b == iAntenna { fkOne(b) }                 // the pack just moved
            let O = worldPoint(wt[b]), T = worldPoint(wt[b] + Quat.rotate(wq[b], springs[i].tip))
            if upright < 0.5 && springs[i].on { springs[i].on = false }
            guard upright >= 0.5, let q = stepSpring(&springs[i], origin: O, target: T, dt: dt) else { continue }
            setWorld(b, Quat.norm(Quat.mul(toModel(q), wq[b])))
            fkOne(b)
        }
        fkOne(iAntenna)
    }

    /// The muzzle (and other sockets) in world space on the posed rig.
    func worldSocket(_ name: String) -> F3? {
        guard let s = asset.sockets[name] else { return nil }
        let p = socket(s)
        let w = world.point(p.x, p.y, p.z)
        return F3(w.x, w.y, w.z)
    }

    /// World-space direction of a bone's local axis (the weapon's +z: where it points).
    func worldAxis(_ bone: Int, _ axis: F3) -> F3 {
        let v = Quat.rotate(wq[bone], axis)
        let c = cosf(yaw), s = sinf(yaw)
        return F3(v.x * c + v.z * s, v.y, -v.x * s + v.z * c)
    }

    /// The skinning palette into `out` (3 float4 rows per bone, world space: the instance transform folded in).
    func writePalette(_ out: UnsafeMutablePointer<SIMD4<Float>>) {
        let c = cosf(yaw), s = sinf(yaw)
        for b in 0..<n {
            let (r0, r1, r2) = Quat.rows(wq[b])
            let t = wt[b] - (r0 * 0 + F3((r0 * asset.bindPos[b]).sum(), (r1 * asset.bindPos[b]).sum(), (r2 * asset.bindPos[b]).sum()))
            // world = Ry(yaw) × M, then + origin
            let w0 = r0 * c + r2 * s, w2 = r0 * -s + r2 * c
            let t0 = t.x * c + t.z * s + origin.x, t2 = -t.x * s + t.z * c + origin.z, t1 = t.y + origin.y
            out[b * 3] = SIMD4(w0.x, w0.y, w0.z, t0)
            out[b * 3 + 1] = SIMD4(r1.x, r1.y, r1.z, t1)
            out[b * 3 + 2] = SIMD4(w2.x, w2.y, w2.z, t2)
        }
    }
