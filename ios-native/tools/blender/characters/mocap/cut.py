"""Authoring tool: cut the source ranges the clips use out of the original downloads into sources/ (unchanged BVH
frames: the header and the frame lines of the range, only the frame count rewritten), sources/manifest.json (each
cut's first-frame time in its original take) and SOURCES.md (URL, licence, sha256 of the original and of the cut,
frame ranges, the clips that use it). Never commit whole takes or datasets: only what CYCLES / IDLES / TURNS sample.

  venv/bin/python -B characters/mocap/cut.py DOWNLOADS_DIR      (DOWNLOADS_DIR: the original files named by take,
                                                                 cmu_35_01.bvh = 35_01.bvh, style_neutral_bw.bvh =
                                                                 neutral_bw.bvh)
Needs Blender's importer only to measure the cycles (clips.used_ranges); run it after any change of those tables."""
import hashlib
import json
import math
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.dirname(HERE))
sys.path.insert(0, os.path.dirname(os.path.dirname(HERE)))

MARGIN = 0.25          # s kept around each used range
CMU_URL = 'https://raw.githubusercontent.com/meshula/cmu-mocap/master/data/{s:03d}/{take}.bvh'
STYLE_URL = 'https://raw.githubusercontent.com/aether-lang-dev/ae3d/main/tests/fixtures/people/100style/{name}.bvh'
CMU_LIC = ('CMU Graphics Lab Motion Capture Database (mocap.cs.cmu.edu), cgspeed 2010 BVH conversion: free to use in '
           'research and commercial products; the data itself may not be resold, even converted')
STYLE_LIC = 'CC BY 4.0 — «The 100STYLE Dataset - Ian Mason» (https://creativecommons.org/licenses/by/4.0/)'


HEAD = """# Motion-capture sources of the marines' clips

Generated by `cut.py` from the original downloads — edit the tables in `clips.py`, never these files by hand. Only the
ranges the clips sample are committed (± 0.25 s), as unchanged BVH frames (header + frame lines; only `Frames:`
rewritten); the build reads them with Blender's own importer (`bvhsrc.py`). No whole take or dataset is in the repo.

| Library | Licence | How we use it |
|---|---|---|
| CMU Graphics Lab Motion Capture Database, cgspeed 2010 BVH conversion (GitHub mirror meshula/cmu-mocap) | Free for research and commercial use; the data may be included in commercially sold products but not resold, even converted. Credit (appreciated, given in `ios-native/CREDITS.md` and the game's credits): «The data used in this project was obtained from mocap.cs.cmu.edu. The database was created with funding from NSF EIA-0196217.» | retargeted into the clips baked into the marines' `.ihv` files; the BVH cuts here are build inputs, never shipped |
| 100STYLE (Mason, Starke, Komura 2022), Neutral style cuts (GitHub mirror aether-lang-dev/ae3d, unchanged frames of the Zenodo release) | CC BY 4.0 — https://creativecommons.org/licenses/by/4.0/ — credit «The 100STYLE Dataset - Ian Mason» (`ios-native/CREDITS.md`, the game's credits, the store description) | as above |
| Quaternius Universal Animation Library | CC0 1.0 | credited; no clip of this package uses it (kept for the actions package) |

Not usable, never added: LAFAN1 (CC BY-NC-ND), Bandai Namco Research Motion (CC BY-NC), AMASS, Motorica, the 4TU CC BY-NC
FBX conversion of CMU. CMU subjects captured at 60 fps but stamped 120 fps by the conversion (e.g. 141, 143) are not used:
every CMU take here is from subjects 09, 35, 69 and 77 (120 fps).

"""


def original_name(take):
    return take.split('_', 1)[1] + '.bvh'


def url_of(take):
    lib, rest = take.split('_', 1)
    if lib == 'cmu':
        return CMU_URL.format(s=int(rest.split('_')[0]), take=rest)
    return STYLE_URL.format(name=rest)


def sha(path):
    return hashlib.sha256(open(path, 'rb').read()).hexdigest()


def cut(src, dst, t0, t1):
    lines = open(src).read().split('\n')
    i = next(k for k, l in enumerate(lines) if l.strip().startswith('Frames:'))
    n = int(lines[i].split()[-1])
    dt = float(lines[i + 1].split()[-1])
    a = max(0, int(math.floor(t0 / dt + 1e-9)))
    b = min(n, int(math.ceil(t1 / dt - 1e-9)) + 1)
    frames = lines[i + 2:i + 2 + n]
    out = lines[:i] + [f'Frames: {b - a}', lines[i + 1]] + frames[a:b] + ['']
    with open(dst, 'w', newline='\n') as fh:
        fh.write('\n'.join(out))
    return a, b, n, dt


def main():
    dl = sys.argv[1]
    os.environ['MOCAP_SRC_DIR'] = dl                         # the clip tables read the originals while cutting
    from mocap import clips as C
    ranges = C.used_ranges()
    by_take = {}
    for nm in C.names():
        if nm in C.LOCO:
            by_take.setdefault(C.CYCLES[C.LOCO[nm][0]]['take'], []).append(nm)
        elif nm in C.IDLES:
            by_take.setdefault(C.IDLES[nm][0], []).append(nm)
        else:
            by_take.setdefault(C.TURNS[nm][0], []).append(nm)
    out_dir = os.path.join(HERE, 'sources')
    os.makedirs(out_dir, exist_ok=True)
    man, rows = {}, []
    for take in sorted(ranges):
        src = os.path.realpath(os.path.join(dl, take + '.bvh'))
        lo = min(a for a, _ in ranges[take]) - MARGIN
        hi = max(b for _, b in ranges[take]) + MARGIN
        dst = os.path.join(out_dir, take + '.bvh')
        a, b, n, dt = cut(src, dst, max(0.0, lo), hi)
        man[take] = dict(file=take + '.bvh', t0=round(a * dt, 6), first=a, frames=b - a, of=n, frame_time=dt,
                         original=original_name(take))
        lib = take.split('_')[0]
        rows.append(f'| `sources/{take}.bvh` | {url_of(take)} | {"CMU" if lib == "cmu" else "100STYLE (CC BY 4.0)"} | '
                    f'{a}–{b - 1} of {n} ({a * dt:.3f}–{(b - 1) * dt:.3f} s at {1 / dt:.0f} fps) | `{sha(src)}` | '
                    f'`{sha(dst)}` | {", ".join(sorted(by_take.get(take, [])))} |')
        print(take, a, b, n, os.path.getsize(dst))
    json.dump(man, open(os.path.join(out_dir, 'manifest.json'), 'w'), indent=1, sort_keys=True)
    doc = HEAD + '\n'.join(
        ['| Committed cut | Original (download URL) | Licence | Frames kept | sha256 of the original | sha256 of the cut | Clips |',
         '|---|---|---|---|---|---|---|'] + rows) + '\n'
    open(os.path.join(HERE, 'SOURCES.md'), 'w').write(doc)


if __name__ == '__main__':
    main()
